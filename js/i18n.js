// Значение параметра: вид (→ его название), {k: ключ} (→ перевод), {k, lower} или примитив
function resolveParam(v) {
  if (v && typeof v === 'object') {
    if (typeof Species !== 'undefined' && v instanceof Species) return v.title;
    if (v.k) { const s = t(v.k); return v.lower ? s.toLowerCase() : s; }
  }
  return v;
}

function t(key, p) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.ru[key];
  if (s === undefined) return key;
  if (p && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => (k in p ? resolveParam(p[k]) : ''));
  return s;
}

function setLang(l) {
  if (!LANGS.includes(l)) return;
  LANG = l;
  try { localStorage.setItem('mikromir.lang', l); } catch (e) { /* no storage */ }
}

// Статический текст в HTML: data-i18n (текст), data-i18n-title (подсказка)
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  document.title = t('doc.title');
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}
